create or replace function public.increment_video_likes(p_video_id uuid)
returns void
language sql
security definer
as $$
    update public.portfolio_videos
    set likes_count = likes_count + 1
    where id = p_video_id;
$$;
grant execute on function public.increment_video_likes(uuid) to anon, authenticated;

