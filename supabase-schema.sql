create extension if not exists pgcrypto;

create table if not exists public.admins (
    user_id uuid primary key references auth.users(id) on delete cascade,
    created_at timestamptz not null default now()
);

create or replace function public.is_croti_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select exists (
        select 1 from public.admins where user_id = auth.uid()
    );
$$;

revoke all on function public.is_croti_admin() from public;
grant execute on function public.is_croti_admin() to anon, authenticated;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

create table if not exists public.portfolio_videos (
    id uuid primary key default gen_random_uuid(),
    title text not null check (char_length(title) between 1 and 100),
    client text not null default '' check (char_length(client) <= 100),
    category text not null check (category in ('featured', 'short', 'vsl')),
    description text not null default '' check (char_length(description) <= 500),
    year integer not null default (extract(year from current_date)::integer) check (year between 2000 and 2100),
    services text[] not null default '{}',
    aspect text not null default 'horizontal' check (aspect in ('horizontal', 'vertical')),
    media_position text not null default '50% 50%' check (char_length(media_position) <= 40),
    video_path text not null unique,
    poster_path text,
    sort_order integer not null default 0 check (sort_order >= 0),
    published boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.portfolio_clients (
    id uuid primary key default gen_random_uuid(),
    name text not null check (char_length(name) between 1 and 100),
    platform text not null default 'instagram' check (platform in ('instagram', 'youtube', 'tiktok')),
    instagram_url text not null check (char_length(instagram_url) between 10 and 300),
    instagram_handle text not null check (char_length(instagram_handle) between 1 and 60),
    followers_count bigint not null default 0 check (followers_count >= 0),
    profile_path text,
    sort_order integer not null default 0 check (sort_order >= 0),
    published boolean not null default true,
    verified boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.portfolio_testimonials (
    id uuid primary key default gen_random_uuid(),
    quote text not null check (char_length(quote) between 10 and 600),
    name text not null check (char_length(name) between 1 and 100),
    role text not null default '' check (char_length(role) <= 120),
    profile_path text,
    sort_order integer not null default 0 check (sort_order >= 0),
    published boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.leads (
    id bigint generated by default as identity primary key,
    name text not null check (char_length(name) between 2 and 100),
    whatsapp text not null check (char_length(whatsapp) between 6 and 30),
    email text not null check (char_length(email) between 5 and 254),
    source text not null default 'portfolio',
    created_at timestamptz not null default now()
);

